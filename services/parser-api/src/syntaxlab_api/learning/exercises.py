"""Exercise bank (``data/exercises/*.yaml``).

Two sources of answer keys, never parser output:

* ``pos`` / ``dependency`` exercises carry **gold annotations** copied from a treebank
  (generated by ``scripts/build_learning_exercises.py``);
* ``constituency`` exercises name a preset grammar; the key is computed at check time as
  **every** parse the Earley parser finds, so any analysis the grammar allows is accepted.
"""

from __future__ import annotations

from pathlib import Path
from typing import Annotated, Literal

import yaml
from pydantic import BaseModel, ConfigDict, Field, ValidationError

from syntaxlab_api.analysis.validate import StructureError, validate_dependency
from syntaxlab_api.grammar.earley import Earley
from syntaxlab_api.grammar.grammar import compile_grammar, tokenize
from syntaxlab_api.grammar.presets import GrammarPreset
from syntaxlab_api.languages.config import ConfigError
from syntaxlab_api.schemas.analysis import DependencyAnalysis, DependencyArc


class _Model(BaseModel):
    model_config = ConfigDict(extra="forbid", frozen=True)


class Source(_Model):
    treebank: str
    release: str
    split: str
    sent_id: str
    license: str


class GoldToken(_Model):
    id: int = Field(ge=1)
    form: str
    upos: str
    head: int = Field(ge=0)
    deprel: str


class _Base(_Model):
    id: str = Field(pattern=r"^[a-z0-9][a-z0-9-]{0,63}$")
    title: str
    difficulty: int = Field(ge=1, le=3)


class PosExercise(_Base):
    kind: Literal["pos"]
    language: str
    source: Source
    tokens: list[GoldToken]


class DependencyExercise(_Base):
    kind: Literal["dependency"]
    language: str
    source: Source
    tokens: list[GoldToken]
    relations: list[str] = Field(min_length=2)


class ConstituencyExercise(_Base):
    kind: Literal["constituency"]
    grammar: str = Field(description="Id of a preset grammar.")
    sentence: str
    instructions: str | None = None


Exercise = Annotated[
    PosExercise | DependencyExercise | ConstituencyExercise, Field(discriminator="kind")
]


class _File(BaseModel):
    exercise: Exercise


KIND_ORDER = {"pos": 0, "dependency": 1, "constituency": 2}


def load_exercises(
    directory: Path, presets: dict[str, GrammarPreset]
) -> dict[str, PosExercise | DependencyExercise | ConstituencyExercise]:
    exercises: dict[str, PosExercise | DependencyExercise | ConstituencyExercise] = {}
    for path in sorted(directory.glob("*.yaml")):
        try:
            item = _File.model_validate(
                {"exercise": yaml.safe_load(path.read_text(encoding="utf-8"))}
            ).exercise
        except (yaml.YAMLError, ValidationError) as exc:
            raise ConfigError(f"invalid exercise {path}: {exc}") from exc
        if item.id != path.stem:
            raise ConfigError(f"exercise {path} declares id {item.id!r}")
        _check(item, presets, path)
        exercises[item.id] = item
    return dict(
        sorted(exercises.items(), key=lambda kv: (KIND_ORDER[kv[1].kind], kv[1].difficulty, kv[0]))
    )


def _check(
    item: PosExercise | DependencyExercise | ConstituencyExercise,
    presets: dict[str, GrammarPreset],
    path: Path,
) -> None:
    if isinstance(item, ConstituencyExercise):
        preset = presets.get(item.grammar)
        if preset is None:
            raise ConfigError(f"exercise {path} uses unknown grammar {item.grammar!r}")
        grammar, _ = compile_grammar(preset.grammar)
        assert grammar is not None  # presets are validated when loaded
        if not Earley(grammar).parse(tokenize(item.sentence)).accepted:
            raise ConfigError(f"exercise {path}: the grammar does not generate {item.sentence!r}")
        return
    ids = [t.id for t in item.tokens]
    if ids != list(range(1, len(ids) + 1)):
        raise ConfigError(f"exercise {path}: token ids must be 1..n")
    try:
        validate_dependency(
            DependencyAnalysis(
                scheme="ud-2",
                arcs=[
                    DependencyArc(dependent=t.id, head=t.head, relation=t.deprel)
                    for t in item.tokens
                ],
            ),
            len(item.tokens),
        )
    except StructureError as exc:
        raise ConfigError(f"exercise {path}: gold tree is invalid: {exc}") from exc
    if isinstance(item, DependencyExercise):
        missing = {t.deprel for t in item.tokens if t.deprel != "root"} - set(item.relations)
        if missing:
            raise ConfigError(
                f"exercise {path}: relation options miss gold labels {sorted(missing)}"
            )
