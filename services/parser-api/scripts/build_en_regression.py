"""Build the English linguistic-regression fixture from UD English-EWT (gold annotations).

Sentences are *selected*, never written: every reference analysis is the treebank's manual
annotation. Categories are assigned by deterministic rules over the gold trees, so the
selection is reproducible:

    uv run python scripts/build_en_regression.py

Source: UD_English-EWT, tag r2.18, test split. License: CC BY-SA 4.0 (see fixture README).
"""

from __future__ import annotations

import urllib.request
from collections import defaultdict
from pathlib import Path

TAG = "r2.18"
URL = f"https://raw.githubusercontent.com/UniversalDependencies/UD_English-EWT/{TAG}/en_ewt-ud-test.conllu"
OUT = Path(__file__).resolve().parents[1] / "tests" / "fixtures" / "ud" / "en_ewt_regression.conllu"
PER_CATEGORY = 12
MIN_WORDS, MAX_WORDS = 5, 25
CLAUSAL = {"advcl", "ccomp", "acl:relcl", "csubj", "xcomp"}


def sentences(text: str) -> list[tuple[list[str], list[list[str]]]]:
    out = []
    for block in text.strip().split("\n\n"):
        comments = [line for line in block.splitlines() if line.startswith("#")]
        rows = [line.split("\t") for line in block.splitlines() if line and line[0].isdigit()]
        out.append((comments, rows))
    return out


def categories(comments: list[str], rows: list[list[str]]) -> set[str]:
    words = [r for r in rows if r[0].isdigit()]  # skip MWT ranges and empty nodes
    text = next((c[9:].strip() for c in comments if c.startswith("# text = ")), "")
    rels = {r[7] for r in words}
    by_id = {r[0]: r for r in words}
    children = defaultdict(list)
    for r in words:
        children[r[6]].append(r)

    cats: set[str] = set()
    if text.endswith("?"):
        cats.add("question")
    if any("Polarity=Neg" in r[5] for r in words):
        cats.add("negation")
    if "nsubj:pass" in rels:
        cats.add("passive")
    if any(r[7] in {"obl", "nmod"} and any(c[7] == "case" for c in children[r[0]]) for r in words):
        cats.add("prepositional_phrase")
    if any(
        r[3] == "NOUN"
        and {"det", "amod"} <= {c[7] for c in children[r[0]]}
        and {"nmod", "acl", "acl:relcl"} & {c[7] for c in children[r[0]]}
        for r in words
    ):
        cats.add("complex_noun_phrase")
    clause_heads = {r[0] for r in words if any(c[7].startswith("nsubj") for c in children[r[0]])}
    if any(r[7] == "conj" and r[0] in clause_heads and r[6] in clause_heads for r in words):
        cats.add("compound_sentence")
    if rels & CLAUSAL:
        cats.add("complex_sentence")
    root = next((r for r in words if r[6] == "0"), None)
    if (
        root is not None
        and text.endswith(".")
        and not (rels & CLAUSAL)
        and "conj" not in rels
        and len(words) <= 10
        and any(c[7] == "nsubj" for c in children[root[0]])
        and by_id[root[0]][3] in {"VERB", "AUX", "ADJ", "NOUN"}
    ):
        cats.add("simple_declarative")
    return cats


def main() -> None:
    with urllib.request.urlopen(URL, timeout=60) as response:
        data = response.read().decode("utf-8")
    chosen: dict[str, list[str]] = defaultdict(list)
    selected: list[tuple[list[str], list[list[str]], set[str]]] = []
    for comments, rows in sentences(data):
        n_words = sum(1 for r in rows if r[0].isdigit())
        if not (MIN_WORDS <= n_words <= MAX_WORDS):
            continue
        if any("." in r[0] for r in rows):  # skip enhanced-only empty nodes
            continue
        cats = categories(comments, rows)
        needed = {c for c in cats if len(chosen[c]) < PER_CATEGORY}
        if not needed:
            continue
        sent_id = next(c for c in comments if c.startswith("# sent_id"))
        for c in cats:
            chosen[c].append(sent_id)
        selected.append((comments, rows, cats))

    OUT.parent.mkdir(parents=True, exist_ok=True)
    with OUT.open("w", encoding="utf-8", newline="\n") as f:
        f.write(f"# source = UD_English-EWT {TAG} en_ewt-ud-test.conllu (CC BY-SA 4.0)\n")
        f.write("# generated by services/parser-api/scripts/build_en_regression.py\n\n")
        for comments, rows, cats in selected:
            for c in comments:
                f.write(c + "\n")
            f.write(f"# syntaxlab_categories = {','.join(sorted(cats))}\n")
            for r in rows:
                f.write("\t".join(r) + "\n")
            f.write("\n")
    print(f"wrote {len(selected)} sentences to {OUT}")
    for cat in sorted(chosen):
        print(f"  {cat:22s} {len(chosen[cat])}")


if __name__ == "__main__":
    main()
